// Token Radar — model radar-2.
//
// One sealed snapshot in, one ranked board out. The board ranks EVERY rankable
// pre-token protocol in the snapshot (the 40 watchlist slugs plus every early
// one below the floor), never a hand-picked subset, and sets the live-token
// protocols aside with the market's own values.
//
// A protocol is pre-token when its DefiLlama record carries no token at all
// (no market cap, no CoinGecko id, no symbol). It is rankable when it is
// pre-token and not a wrapped, staked or bridged product of a token that
// already trades: not a Bridge / Canonical Bridge / Liquid Staking / Liquid
// Restaking / Restaked BTC / CEX category, no whole word wrapped, staked or
// staking in its name, no exchange's name at the start, and no version marker
// (a name ending in V2 / 2.0 is a pool of another protocol, not a launch of
// its own). WBTC is Bitcoin on Ethereum and Binance staked ETH is ETH in
// Binance's staking product; neither is a protocol still waiting on a launch
// of its own. No protocol name is ever special-cased: one function scores
// every row.
//
// Implied value — the entry's own claim, computed only from snapshot fields:
//
//   baseMultiple = median(mcap_usd / tvl_usd) over live-token protocols
//                  (category CEX excluded), clamped to [0.05, 0.50].
//                  The market itself prices live tokens against the TVL they
//                  secure; the median is the calibration, not a guess.
//   growthPct    = clamp(change_7d ?? 0, -50, 150)
//   growthMult   = 1 + growthPct / 100 * 0.6          (0.70 .. 1.90)
//   maturityMult = 0.70 + min(age_days ?? 365, 1460) / 1460 * 0.30
//                  (0.70 .. 1.00). Age is days since DefiLlama first listed
//                  the protocol: how long it has run with no token on record.
//   chainMult    = min(1 + 0.05 * ln(chainCount), 1.25); 1 chain -> 1.00.
//                  More chains = a wider footprint for the same TVL.
//   implied      = max(1, round(tvl_usd * baseMultiple
//                          * growthMult * maturityMult * chainMult))
//
// On this snapshot the live median is about 0.20, so a $1B-TVL protocol that is
// flat over 7 days, ~1 year old and on 2 chains is worth roughly
// 1e9 * 0.20 * 1.00 * 0.775 * 1.035 ≈ $160M of implied value. The dashboard
// recomputes every row from the same figures and shows each multiplier, so the
// page, the board and this file always agree.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
